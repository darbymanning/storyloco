import path from "node:path"
import type { Component } from "./local.js"
import { plugin_types } from "./plugins.js"
import { allowed } from "../editor/content.js"

export function type_name(name: string) {
	const clean = name
		.replace(/[^a-z0-9]/gi, "_")
		.replace(/_+/g, "_")
		.replace(/^_+|_+$/g, "")
	const camel = clean
		.replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase())
		.replace(/_/g, "")
	const pascal = camel ? camel[0].toUpperCase() + camel.slice(1) : ""
	return /^\d/.test(pascal) ? `_${pascal}` : pascal
}

function specifier(from: string, to: string) {
	const relative = path
		.relative(path.dirname(from), to)
		.split(path.sep)
		.join("/")
		.replace(/\.ts$/, ".js")
	return relative.startsWith(".") ? relative : `./${relative}`
}

/** Render interfaces directly; field values come from the shared schema package. */
export function generate_types(
	components: Component[],
	output: string,
	root: string,
	entry?: string,
	named = true
) {
	const nestable = components.map((c) => ({ ...c, is_nestable: c.is_nestable !== false })) as Array<
		Parameters<typeof allowed>[0][number]
	>
	const names = new Map<string, string>()
	const used = new Set([
		"StoryblokAsset",
		"StoryblokMultiasset",
		"StoryblokMultilink",
		"StoryblokRichtext",
		"StoryblokTable",
		"Blok",
		"ContentTypes",
		"ContentType",
		"StoryblokCustomPlugins",
		"FieldValue",
		"Field",
		"Richtext",
		"RichTextFieldValue",
		"Schema",
		"Model",
		"PluginValue",
	])

	for (const component of components) {
		const name = type_name(component.name)
		if (!name || used.has(name))
			throw new Error(
				`Block ${JSON.stringify(component.name)} produces a conflicting TypeScript name ${name}`
			)
		used.add(name)
		names.set(component.name, name)
	}

	const custom = components.some((c) => Object.values(c.schema).some((f) => f.type === "custom"))

	const lines = [
		"// AUTO-GENERATED by storyloco. DO NOT EDIT.",
		"",
		'import type {} from "storyloco"',
		'import type { FieldValue, Field, Schema, RichTextFieldValue } from "storyloco/schema"',
		"",
		"export type { FieldValue, Field, Schema, RichTextFieldValue }",
		'export type StoryblokMultiasset = import("storyloco/schema").AssetFieldValue[]',
		"",
	]
	if (entry) {
		lines.push(
			`import type { ${named ? "schema as model" : "default as model"} } from ${JSON.stringify(specifier(output, entry))}`,
			"type Model = Schema<typeof model>",
			'export type StoryblokCustomPlugins = Model["fieldPlugins"]'
		)
	} else if (custom)
		lines.push(
			`import type { StoryblokCustomPlugins } from ${JSON.stringify(specifier(output, path.join(root, "vite.config.ts")))}`
		)
	else lines.push("export interface StoryblokCustomPlugins {}")
	lines.push(
		"",
		`export type Richtext<T, B> =
			T extends readonly (infer E)[] ? Richtext<E, B>[] :
			T extends { type: "blok"; attrs: infer A }
				? Omit<T, "attrs"> & { attrs: Omit<A, "body"> & { body: Array<B & { component: string }> | null } } :
			T extends object
				? { [K in keyof T]: K extends "content" ? Richtext<T[K], B> : T[K] } : T`,
		"",
		"export type PluginValue<K extends string, Known = unknown> = K extends keyof StoryblokCustomPlugins ? StoryblokCustomPlugins[K] : Known",
		"export type Blok<T> = T & { component?: string; _uid?: string; _editable?: string }",
		'/** A link, with the story it points to once links are resolved (`resolve_links: "url"`); the schema\'s own allows only strings beside its fields */',
		"type StoryRef = { name?: string; uuid?: string; slug?: string; full_slug?: string; url?: string; [key: string]: unknown }",
		'export type StoryblokLink = import("storyloco/schema").MultilinkFieldValue extends infer L ? L extends unknown ? { [K in keyof L as string extends K ? never : K]: L[K] } & { story?: StoryRef } : never : never',
		"/** What a multilink field holds, by the name a site annotates one with */",
		"export type StoryblokMultilink = StoryblokLink",
		'export type { AssetFieldValue as StoryblokAsset, RichTextFieldValue as StoryblokRichtext, TableFieldValue as StoryblokTable } from "storyloco/schema"'
	)

	for (const component of components) {
		lines.push(
			"",
			`export interface ${names.get(component.name)} {`,
			`component?: ${JSON.stringify(component.name)}`,
			"_uid?: string",
			"_editable?: string"
		)

		for (const [key, field] of Object.entries(component.schema)) {
			if (["tab", "section", "group"].includes(String(field.type))) continue

			let value: string
			if (field.type === "bloks" || (field.type === "richtext" && field.restrict_components)) {
				// by name, folder or tag, as the editor offers them; a block is nestable unless it says not
				const types = allowed(nestable, field as Parameters<typeof allowed>[1]).map((c) =>
					names.get(c.name)!
				)
				value =
					field.type === "bloks"
						? `(${types.join(" | ") || "never"})[]`
						: // still a richtext as the schema has it, so it goes wherever one does, with its bloks typed
							`RichTextFieldValue & Richtext<RichTextFieldValue, ${types.join(" | ") || "never"}>`
			} else if (field.type === "multilink") {
				value = "StoryblokLink"
			} else if (
				(field.type === "options" || field.type === "option") &&
				field.source === "internal_stories"
			) {
				// stories it picks: their uuids, or the stories themselves once relations are resolved
				const types = [field.filter_content_type ?? []]
					.flat()
					.map((name) => names.get(String(name)))
					.filter(Boolean)
				// of the types it's limited to; any type's content, as Storyblok's own story types it, when it isn't
				const story = `import("storyloco").Story<${types.join(" | ") || 'import("storyloco").Content'}> | string`
				value = field.type === "options" ? `(${story})[]` : story
			} else if (field.type === "custom") {
				// A registered field plugin wins; Storyloco's own plugins are typed without one
				const plugin = String(field.field_type ?? "")
				const known = Object.hasOwn(plugin_types, plugin)
					? plugin_types[plugin as keyof typeof plugin_types]
					: undefined
				value = `PluginValue<${JSON.stringify(plugin)}${known ? `, ${known}` : ""}>`
			} else {
				// only what types its value: the rest (its id, limits, appearance) is the space's own, as
				// the Management API spells it, and one that isn't as the schema types say, like a number
				// for `max_options`, would make the field `never`
				const typing = Object.fromEntries(
					Object.entries(field).filter(([name]) => ["type", "source", "options"].includes(name))
				)
				value = `FieldValue<Extract<Field, { type: ${JSON.stringify(field.type)} }> & ${JSON.stringify(typing)}>`
			}
			lines.push(`${JSON.stringify(key)}${field.required ? "" : "?"}: ${value}`)
		}
		lines.push("}")
	}
	lines.push(
		"",
		"export interface ContentTypes {",
		...components
			.filter((c) => c.is_root)
			.map((c) => `${JSON.stringify(c.name)}: ${names.get(c.name)}`),
		"}",
		"export type ContentType = ContentTypes[keyof ContentTypes]",
		'declare module "storyloco" { interface Registry extends ContentTypes {} }',
		'declare module "storyloco/schema" { interface Blocks {',
		...components.map((c) => `${JSON.stringify(c.name)}: ${names.get(c.name)}`),
		"} }"
	)
	return lines.join("\n") + "\n"
}
